"""
Generate Hybrid Model Predictions for Offline Analysis.

This script generates predictions using the hybrid model selection strategy,
outputting in the same format as the champion evaluation pipeline for 
compatibility with existing analysis workbooks.

Strategy: Use existing prediction files from Champion and Context models,
then blend them based on regime detection for each date.

Usage:
    python generate_hybrid_predictions.py
    python generate_hybrid_predictions.py --champion-preds PATH --context-preds PATH --output PATH
"""

import argparse
import pandas as pd
import numpy as np
from pathlib import Path

from hybrid_model_selector import VarianceRegimeDetector, RegimeConfig


def main():
    parser = argparse.ArgumentParser(description="Generate hybrid predictions")
    parser.add_argument("--data", type=str, default=None,
                        help="Input data file (not used, for compatibility)")
    parser.add_argument("--champion-preds", type=str, 
                        default="predictions/current_season_champion_2025_2026_predictions.csv",
                        help="Path to Champion predictions CSV")
    parser.add_argument("--context-preds", type=str,
                        default="predictions/current_season_context_2025_2026_predictions.csv",
                        help="Path to Context predictions CSV")
    parser.add_argument("--output", type=str,
                        default="predictions/current_season_hybrid_2025_2026_predictions.csv",
                        help="Output path for hybrid predictions")
    args = parser.parse_args()
    
    print("="*70)
    print("  HYBRID MODEL PREDICTION GENERATION")
    print("="*70)
    
    # Use existing prediction files (generated by predict_margin.py)
    champion_preds_path = Path(args.champion_preds)
    context_preds_path = Path(args.context_preds)
    output_path = Path(args.output)
    
    # Load existing predictions
    print("\nLoading existing predictions...")
    
    if not champion_preds_path.exists():
        print(f"ERROR: Champion predictions not found at {champion_preds_path}")
        print("Run: .\\evaluate_current_season_champion.ps1")
        return
    
    if not context_preds_path.exists():
        print(f"ERROR: Context predictions not found at {context_preds_path}")
        print("Run: python run_experiment_context.py")
        return
    
    champion_df = pd.read_csv(champion_preds_path)
    context_df = pd.read_csv(context_preds_path)
    
    print(f"  Champion: {len(champion_df)} games from {champion_preds_path}")
    print(f"  Context:  {len(context_df)} games from {context_preds_path}")
    
    # Parse dates
    champion_df['date'] = pd.to_datetime(champion_df['date'])
    context_df['date'] = pd.to_datetime(context_df['date'])
    
    # Initialize regime detector with optimal parameters
    config = RegimeConfig(
        min_games_for_detection=250,
        high_variance_threshold=1.30,
        normal_variance_threshold=1.20,
        consecutive_days_required=5,
    )
    detector = VarianceRegimeDetector(config)
    
    # Create context lookup by game_id
    context_by_id = context_df.set_index('game_id').to_dict('index')
    
    # Generate hybrid predictions
    print("\nGenerating hybrid predictions based on regime detection...")
    
    results = []
    history = []
    regime_switches = []
    current_model = 'champion'
    
    # Get unique dates sorted
    dates = sorted(champion_df['date'].unique())
    
    for date in dates:
        date_str = date.strftime('%Y-%m-%d')
        
        # Detect regime for this date
        regime, details = detector.detect_regime('2025-2026', date_str, history)
        history.append(details)
        
        # Determine model to use
        if regime == 'high':
            model_to_use = 'context'
        else:
            model_to_use = 'champion'
        
        # Track regime switches
        if model_to_use != current_model:
            regime_switches.append({
                'date': date_str,
                'from': current_model,
                'to': model_to_use,
                'ratio': details.get('ratio_deff'),
            })
            current_model = model_to_use
        
        # Get games for this date
        day_games = champion_df[champion_df['date'] == date]
        
        for _, row in day_games.iterrows():
            game_id = row['game_id']
            
            if model_to_use == 'champion':
                # Use champion prediction
                pred_margin = row['pred_margin_mu']
            else:
                # Use context prediction if available
                if game_id in context_by_id:
                    pred_margin = context_by_id[game_id]['pred_margin_mu']
                else:
                    # Fallback to champion
                    pred_margin = row['pred_margin_mu']
                    model_to_use = 'champion (fallback)'
            
            results.append({
                'game_id': game_id,
                'date': date_str,
                'game_time': row.get('game_time', ''),
                'away_team': row.get('away_team', ''),
                'home_team': row.get('home_team', ''),
                'market_spread_home': row['market_spread_home'],
                'baseline_margin': row.get('baseline_margin', -row['market_spread_home']),
                'pred_margin_mu': pred_margin,
                'moneyline_home': row.get('moneyline_home', np.nan),
                'moneyline_away': row.get('moneyline_away', np.nan),
                'actual_margin': row.get('actual_margin', np.nan),
                'model_used': model_to_use,
                'regime': regime,
                'variance_ratio': details.get('ratio_deff'),
            })
    
    # Create DataFrame
    df = pd.DataFrame(results)
    
    # Print regime switch summary
    print("\n" + "-"*70)
    print("  REGIME SWITCHES")
    print("-"*70)
    if regime_switches:
        for switch in regime_switches:
            ratio_str = f"{switch['ratio']:.3f}" if switch['ratio'] else "N/A"
            print(f"  {switch['date']}: {switch['from']} -> {switch['to']} (ratio={ratio_str})")
    else:
        print("  No regime switches detected")
    
    # Calculate performance metrics
    print("\n" + "-"*70)
    print("  PERFORMANCE SUMMARY")
    print("-"*70)
    
    valid = df.dropna(subset=['actual_margin'])
    
    if len(valid) > 0:
        # Overall metrics
        mae = (valid['actual_margin'] - valid['pred_margin_mu']).abs().mean()
        
        pred_covers = valid['pred_margin_mu'] + valid['market_spread_home'] > 0
        actual_covers = valid['actual_margin'] + valid['market_spread_home'] > 0
        ats_correct = (pred_covers == actual_covers).sum()
        ats_total = len(valid)
        ats_pct = 100 * ats_correct / ats_total
        
        print(f"\n  Overall ({ats_total} games):")
        print(f"    MAE: {mae:.3f} points")
        print(f"    ATS: {ats_pct:.2f}% ({ats_correct}/{ats_total})")
        
        # By model used
        print(f"\n  By Model Used:")
        for model in valid['model_used'].unique():
            model_games = valid[valid['model_used'] == model]
            model_pred_covers = model_games['pred_margin_mu'] + model_games['market_spread_home'] > 0
            model_actual_covers = model_games['actual_margin'] + model_games['market_spread_home'] > 0
            model_correct = (model_pred_covers == model_actual_covers).sum()
            model_total = len(model_games)
            model_pct = 100 * model_correct / model_total if model_total > 0 else 0
            print(f"    {model}: {model_pct:.2f}% ({model_correct}/{model_total})")
        
        # Compare to pure champion
        champ_valid = champion_df.dropna(subset=['actual_margin'])
        champ_pred_covers = champ_valid['pred_margin_mu'] + champ_valid['market_spread_home'] > 0
        champ_actual_covers = champ_valid['actual_margin'] + champ_valid['market_spread_home'] > 0
        champ_correct = (champ_pred_covers == champ_actual_covers).sum()
        champ_total = len(champ_valid)
        champ_pct = 100 * champ_correct / champ_total
        
        print(f"\n  Comparison:")
        print(f"    Pure Champion: {champ_pct:.2f}% ({champ_correct}/{champ_total})")
        print(f"    Hybrid:        {ats_pct:.2f}% ({ats_correct}/{ats_total})")
        print(f"    Improvement:   {ats_pct - champ_pct:+.2f}%")
    
    # Save predictions
    output_path.parent.mkdir(exist_ok=True)
    df.to_csv(output_path, index=False)
    print(f"\n  Predictions saved to: {output_path}")
    
    # Also save a version without the extra columns for compatibility
    compat_df = df[['game_id', 'date', 'game_time', 'away_team', 'home_team', 
                    'market_spread_home', 'baseline_margin', 'pred_margin_mu',
                    'moneyline_home', 'moneyline_away', 'actual_margin']].copy()
    compat_path = output_path.parent / "current_season_hybrid_2025_2026_predictions_compat.csv"
    compat_df.to_csv(compat_path, index=False)
    print(f"  Compatible format saved to: {compat_path}")
    
    print("\n" + "="*70)
    print("  HYBRID PREDICTION GENERATION COMPLETE")
    print("="*70)


if __name__ == "__main__":
    main()
